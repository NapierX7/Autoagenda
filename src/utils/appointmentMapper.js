/** Colunas necessárias para `mapAppointmentRecord` (contrato da UI). */
export const APPOINTMENT_ROW_SELECT = [
  'id',
  'appointment_date',
  'appointment_time',
  'customer_name',
  'customer_phone',
  'customer_cpf',
  'customer_zip_code',
  'customer_email',
  'customer_address',
  'seller_name',
  'seller_email',
  'vehicle_plate',
  'vehicle_model',
  'vehicle_year',
  'notes',
  'status',
  'company_id',
  'created_by',
  'is_voucher',
  'voucher_approved_at',
  'voucher_approved_by',
  'laudo_result',
  'laudo_rejection_reason',
  'laudo_file_url',
  'laudo_file_name',
  'laudo_finalized_at',
  'laudo_finalized_by',
  'original_appointment_date',
  'original_appointment_time',
  'rescheduled_count',
  'is_encaixe',
  'encaixe_created_at',
  'encaixe_created_by',
  'cancellation_requested_at',
  'cancellation_requested_by',
  'cancellation_request_reason',
  'cancellation_admin_approved_at',
  'cancellation_admin_approved_by',
  'cancellation_evaluator_approved_at',
  'cancellation_evaluator_approved_by',
].join(', ');

export function mapAppointmentRecord(record) {
  if (!record || typeof record !== 'object') return null;
  const timeRaw = record.appointment_time ?? record.time ?? null;
  return {
    id: record.id,
    time: timeRaw != null ? String(timeRaw).slice(0, 5) : '',
    status: record.status,
    customerName: record.customer_name ?? record.customerName ?? '',
    customerPhone: record.customer_phone ?? record.customerPhone ?? '',
    customerCpf: record.customer_cpf ?? record.customerCpf ?? null,
    customerZipCode: record.customer_zip_code ?? record.customerZipCode ?? null,
    customerEmail: record.customer_email ?? record.customerEmail ?? null,
    customerAddress: record.customer_address ?? record.customerAddress ?? null,
    sellerName: record.seller_name ?? record.sellerName ?? '',
    sellerEmail: record.seller_email ?? record.sellerEmail ?? null,
    vehiclePlate: record.vehicle_plate ?? record.vehiclePlate ?? '',
    vehicleModel: record.vehicle_model ?? record.vehicleModel ?? '',
    vehicleYear: record.vehicle_year != null || record.vehicleYear != null
      ? String(record.vehicle_year ?? record.vehicleYear)
      : '',
    notes: record.notes ?? null,
    appointmentDate: record.appointment_date ?? record.appointmentDate ?? null,
    cancellationRequestedAt: record.cancellation_requested_at ?? record.cancellationRequestedAt ?? null,
    cancellationRequestedBy: record.cancellation_requested_by ?? record.cancellationRequestedBy ?? null,
    cancellationRequestReason: record.cancellation_request_reason ?? record.cancellationRequestReason ?? null,
    cancellationAdminApprovedAt: record.cancellation_admin_approved_at ?? record.cancellationAdminApprovedAt ?? null,
    cancellationAdminApprovedBy: record.cancellation_admin_approved_by ?? record.cancellationAdminApprovedBy ?? null,
    cancellationEvaluatorApprovedAt:
      record.cancellation_evaluator_approved_at ?? record.cancellationEvaluatorApprovedAt ?? null,
    cancellationEvaluatorApprovedBy:
      record.cancellation_evaluator_approved_by ?? record.cancellationEvaluatorApprovedBy ?? null,
    isVoucher: Boolean(record.is_voucher ?? record.isVoucher),
    voucherApprovedAt: record.voucher_approved_at ?? record.voucherApprovedAt ?? null,
    voucherApprovedBy: record.voucher_approved_by ?? record.voucherApprovedBy ?? null,
    laudoResult: record.laudo_result ?? record.laudoResult ?? null,
    laudoRejectionReason: record.laudo_rejection_reason ?? record.laudoRejectionReason ?? null,
    laudoFileUrl: record.laudo_file_url ?? record.laudoFileUrl ?? null,
    laudoFileName: record.laudo_file_name ?? record.laudoFileName ?? null,
    laudoFinalizedAt: record.laudo_finalized_at ?? record.laudoFinalizedAt ?? null,
    laudoFinalizedBy: record.laudo_finalized_by ?? record.laudoFinalizedBy ?? null,
    originalAppointmentDate: record.original_appointment_date ?? record.originalAppointmentDate ?? null,
    originalAppointmentTime: (() => {
      const raw = record.original_appointment_time ?? record.originalAppointmentTime ?? null;
      return raw != null ? String(raw).slice(0, 5) : null;
    })(),
    rescheduledCount: record.rescheduled_count ?? record.rescheduledCount ?? 0,
    createdBy: record.created_by ?? record.createdBy ?? null,
    isEncaixe: Boolean(record.is_encaixe ?? record.isEncaixe),
    encaixeCreatedAt: record.encaixe_created_at ?? record.encaixeCreatedAt ?? null,
    encaixeCreatedBy: record.encaixe_created_by ?? record.encaixeCreatedBy ?? null,
  };
}
